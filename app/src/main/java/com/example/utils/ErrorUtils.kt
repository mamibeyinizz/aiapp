package com.example.utils

import com.google.firebase.auth.FirebaseAuthException

object ErrorUtils {

    fun parseError(e: Throwable?, defaultFallback: String = "Bir hata oluştu, tekrar deneyin"): String {
        if (e == null) return defaultFallback

        // 1. Check FirebaseAuthException
        if (e is FirebaseAuthException) {
            val code = (e.errorCode ?: "").lowercase()
            val msg = (e.message ?: "").lowercase()

            if (code.contains("wrong-password") ||
                code.contains("user-not-found") ||
                code.contains("invalid-credential") ||
                code.contains("wrong_password") ||
                code.contains("user_not_found") ||
                code.contains("invalid_credential") ||
                code.contains("user_mismatch") ||
                msg.contains("wrong-password") ||
                msg.contains("user-not-found") ||
                msg.contains("invalid-credential") ||
                msg.contains("invalid_login_credentials") ||
                msg.contains("password is invalid") ||
                msg.contains("no user record")
            ) {
                return "Kullanıcı adı veya şifre hatalı"
            }

            if (code.contains("network-request-failed") ||
                code.contains("network_request_failed") ||
                msg.contains("network")
            ) {
                return "Bağlantı hatası, tekrar deneyin"
            }

            if (code.contains("too-many-requests") ||
                code.contains("too_many_requests") ||
                msg.contains("too many requests")
            ) {
                return "Çok fazla deneme yapıldı, lütfen biraz bekleyin"
            }

            if (code.contains("invalid-email") ||
                code.contains("invalid_email") ||
                msg.contains("invalid email") ||
                msg.contains("badly formatted")
            ) {
                return "Giriş bilgileri geçersiz"
            }

            if (code.contains("email-already-in-use") ||
                code.contains("email_already_in_use")
            ) {
                return "Bu kullanıcı veya e-posta zaten kullanımda"
            }

            if (code.contains("user-disabled")) {
                return "Kullanıcı hesabı devre dışı bırakılmış"
            }
        }

        val rawMsg = e.message ?: ""
        val lowerMsg = rawMsg.lowercase()

        // 2. Check exception message text for known patterns
        if (lowerMsg.contains("wrong-password") ||
            lowerMsg.contains("user-not-found") ||
            lowerMsg.contains("invalid-credential") ||
            lowerMsg.contains("invalid_login_credentials") ||
            lowerMsg.contains("password is invalid") ||
            lowerMsg.contains("no user record") ||
            lowerMsg.contains("there is no user")
        ) {
            return "Kullanıcı adı veya şifre hatalı"
        }

        if (lowerMsg.contains("network-request-failed") ||
            lowerMsg.contains("network_request_failed") ||
            lowerMsg.contains("network error") ||
            lowerMsg.contains("failed to connect") ||
            lowerMsg.contains("unknownhostexception") ||
            lowerMsg.contains("sockettimeoutexception") ||
            lowerMsg.contains("ioexception") ||
            lowerMsg.contains("unable to resolve host") ||
            lowerMsg.contains("unavailable") ||
            lowerMsg.contains("a network error")
        ) {
            return "Bağlantı hatası, tekrar deneyin"
        }

        if (lowerMsg.contains("too-many-requests") ||
            lowerMsg.contains("too_many_requests") ||
            lowerMsg.contains("too many requests")
        ) {
            return "Çok fazla deneme yapıldı, lütfen biraz bekleyin"
        }

        if (lowerMsg.contains("invalid-email") ||
            lowerMsg.contains("invalid_email") ||
            lowerMsg.contains("badly formatted")
        ) {
            return "Giriş bilgileri geçersiz"
        }

        if (lowerMsg.contains("permission_denied") ||
            lowerMsg.contains("permission-denied") ||
            lowerMsg.contains("insufficient permissions")
        ) {
            return "Erişim izniniz yok"
        }

        if (lowerMsg.contains("not_found") ||
            lowerMsg.contains("not-found")
        ) {
            return "Kayıt bulunamadı"
        }

        if (lowerMsg.contains("already_exists") ||
            lowerMsg.contains("already-exists")
        ) {
            return "Bu kayıt zaten mevcut"
        }

        // 3. If it's already a custom Turkish message generated by app logic, preserve it
        if (isTurkishText(rawMsg)) {
            return rawMsg
        }

        // 4. Default fallback
        return defaultFallback
    }

    fun safeUiAction(
        context: android.content.Context? = null,
        errorMessage: String? = null,
        action: () -> Unit
    ) {
        try {
            action()
        } catch (e: Exception) {
            android.util.Log.e("SafeUiAction", "Error during UI action: ${e.message}", e)
            if (context != null) {
                val msg = errorMessage ?: parseError(e, "İşlem sırasında bir hata oluştu")
                try {
                    android.widget.Toast.makeText(context, msg, android.widget.Toast.LENGTH_SHORT).show()
                } catch (t: Throwable) {
                    // Ignore toast failures if context is invalid
                }
            }
        }
    }

    private fun isTurkishText(text: String): Boolean {
        if (text.isBlank()) return false
        val trChars = charArrayOf('ç', 'Ç', 'ğ', 'Ğ', 'ı', 'İ', 'ö', 'Ö', 'ş', 'Ş', 'ü', 'Ü')
        if (trChars.any { text.contains(it) }) return true

        val lower = text.lowercase()
        val trKeywords = listOf(
            "hata", "boş", "olamaz", "bulunamadı", "geçersiz", "oturum", "zaten",
            "vardiya", "şube", "yetki", "konum", "mola", "garson", "masa", "kullanıcı",
            "başarısız", "onay", "deneyin", "bağlantı", "izni", "silindi", "eklendi",
            "güncellendi", "oluşturuldu", "gerekli", "seçin", "işyerinde", "restorana", "seçiniz"
        )
        return trKeywords.any { lower.contains(it) }
    }
}
